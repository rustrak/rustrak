// `.rustrak/lib.rs`: the plugin's crate root, written from the files under
// src/server/. Rust compiles only the modules a file declares; the author
// writes none of those declarations, the folders are the tree.

import { existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { paths } from './config.ts';

const MODULE = /^[a-z][a-z0-9_]*$/;

/**
 * One folder's modules: its folders first, then its files. `at` prefixes
 * each `#[path]`: the top level is reached from .rustrak/, the rest from
 * the folder above.
 */
function declare(
  dir: string,
  shown: string,
  indent: string,
  at = '',
): string[] {
  const entries = readdirSync(dir).sort();
  const dirs = entries.filter((e) => statSync(join(dir, e)).isDirectory());
  const isDir = new Set(dirs);
  const files = entries.filter((e) => e.endsWith('.rs') && !isDir.has(e));
  const lines: string[] = [];
  const named = (entry: string, name: string) => {
    if (name === 'mod' || name === 'lib') {
      throw new Error(
        `${shown}/${entry}: Rustrak declares the modules of src/server; remove it`,
      );
    }
    if (!MODULE.test(name))
      throw new Error(`${shown}/${entry}: a module name is snake_case`);
  };
  for (const sub of dirs) {
    named(sub, sub);
    const inner = declare(join(dir, sub), `${shown}/${sub}`, `${indent}    `);
    if (inner.length === 0) continue;
    lines.push(
      `${indent}#[path = "${at}${sub}"]`,
      `${indent}pub mod ${sub} {`,
      ...inner,
      `${indent}}`,
    );
  }
  for (const file of files) {
    const name = file.slice(0, -'.rs'.length);
    named(file, name);
    lines.push(
      `${indent}#[path = "${at}${file}"]`,
      `${indent}pub mod ${name};`,
    );
  }
  return lines;
}

/** The crate root for `src/server/`, as `.rustrak/lib.rs`. */
export function serverTree(projectDir: string): string {
  const root = paths(projectDir).server;
  const tree = existsSync(root)
    ? declare(root, 'src/server', '', '../src/server/')
    : [];
  return [
    '// Generated by rustrak-plugin from src/server/. Do not edit.',
    '//',
    '// Every plugin has the same shape: routes/ (its HTTP routes, one file per',
    '// resource) and models/ (its data and the queries on it). Settings and',
    '// permissions come from rustrak.config.ts.',
    '',
    'rustrak_plugin::config!();',
    '',
    ...tree,
    '',
  ].join('\n');
}
