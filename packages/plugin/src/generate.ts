// `.rustrak/`: what rustrak.config.ts and src/messages/ mean to the code. The
// server reads `plugin.rs` through `rustrak_plugin::config!()`; the editor
// reads `plugin-env.d.ts`. Written by `build`, and by `generate` on its own.

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { type PluginConfig, paths } from './config.ts';
import {
  keys,
  type Messages,
  missingKeys,
  missingLocales,
  readMessages,
} from './messages.ts';
import { permissionsRust, permissionsTs } from './permissions.ts';
import { serverTree } from './server-tree.ts';
import { settingsRust, settingsTs } from './settings.ts';

export interface Generated {
  warnings: string[];
  /** src/messages/, by locale. */
  messages: Record<string, Messages>;
}

export function generate(dir: string, config: PluginConfig): Generated {
  const settings = config.settings ?? {};
  const permissions = config.permissions ?? {};
  const messages = readMessages(dir);
  const known = new Set(keys(messages.en ?? {}));
  const unlabelled = Object.keys(settings)
    .filter((key) => !known.has(`settings.${key}.label`))
    .map(
      (key) =>
        `src/messages/en.json has no settings.${key}.label (the key is shown)`,
    );

  const tree = serverTree(dir);
  const out = paths(dir).generated;
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'lib.rs'), tree);
  writeFileSync(
    join(out, 'plugin-env.d.ts'),
    [
      '// Generated by rustrak-plugin from rustrak.config.ts and src/messages/. Do not edit.',
      "import '@rustrak/plugin/ui';",
      '',
      "declare module '@rustrak/plugin/ui' {",
      '  interface PluginMessages {',
      ...[...known].sort().map((key) => `    '${key}': true;`),
      '  }',
      settingsTs(settings),
      permissionsTs(permissions),
      '}',
      '',
    ].join('\n'),
  );
  writeFileSync(
    join(out, 'plugin.rs'),
    `// Generated by rustrak-plugin from rustrak.config.ts. Do not edit.\n\n${settingsRust(settings)}\n${permissionsRust(permissions)}`,
  );
  const languages =
    Object.keys(messages).length > 0
      ? missingLocales(
          (l) => l in messages,
          (l) => `src/messages/${l}.json`,
        )
      : [];
  return {
    warnings: [...languages, ...missingKeys(messages), ...unlabelled],
    messages,
  };
}
