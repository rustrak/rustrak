// What `rustrak-plugin build` (and `generate`, for the editor) writes from
// rustrak.config.ts and messages/: the types both sides of the plugin read.

import {
  cpSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import type { PluginConfig } from '../src/config.ts';
import { generate } from '../src/generate.ts';

const fixture = resolve(import.meta.dirname, 'fixtures/ui-plugin');

const config: PluginConfig = {
  name: 'Demo',
  rustrak: '>=0.33.0',
  settings: {
    greeting: { type: 'text', default: 'Hello' },
    apiKey: { type: 'secret' },
  },
};

function run(c: PluginConfig = config) {
  const dir = mkdtempSync(join(tmpdir(), 'rustrak-gen-'));
  cpSync(fixture, dir, { recursive: true });
  const result = generate(dir, c);
  const read = (f: string) => readFileSync(join(dir, '.rustrak', f), 'utf8');
  return { result, env: read('plugin-env.d.ts'), rust: read('plugin.rs') };
}

describe('generate', () => {
  it('types the message keys and the settings for the editor', () => {
    const { env } = run();
    expect(env).toContain("declare module '@rustrak/plugin/ui'");
    expect(env).toContain('"nav.visits": true;');
    expect(env).toContain('greeting: string;');
    expect(env).not.toContain('apiKey');
  });

  it("writes the server's Settings for rustrak_plugin::config!()", () => {
    const { rust } = run();
    expect(rust).toContain(
      '// Generated by rustrak-plugin from rustrak.config.ts',
    );
    expect(rust).toContain('pub greeting: String,');
    expect(rust).toContain('pub api_key: Option<String>,');
  });

  it('writes a Rust keyword as a raw identifier, keeping the setting key', () => {
    const { rust } = run({ ...config, settings: { type: { type: 'text' } } });
    expect(rust).toContain('pub r#type: Option<String>,');
  });

  it('refuses a select whose enum would clash with a generated type', () => {
    expect(() =>
      run({
        ...config,
        settings: { option: { type: 'select', options: ['a', 'b'] } },
      }),
    ).toThrow(/settings\.option: .*clashes with Option/);
    expect(() =>
      run({
        ...config,
        settings: { perm: { type: 'select', options: ['a', 'b'] } },
      }),
    ).toThrow(/settings\.perm: .*clashes with Perm/);
  });

  it('warns about a language missing, a key missing, and a setting with no label', () => {
    const { result } = run();
    expect(result.warnings).toEqual([
      'src/messages/zh.json is missing: readers in zh see English',
      'src/messages/fr.json is missing: readers in fr see English',
      'src/messages/ro.json is missing: readers in ro see English',
      'src/messages/es.json is missing nav.overview (English is shown)',
      'src/messages/en.json has no settings.greeting.label (the key is shown)',
      'src/messages/en.json has no settings.apiKey.label (the key is shown)',
    ]);
  });
});

describe('the server module tree', () => {
  function server(files: string[]) {
    const dir = mkdtempSync(join(tmpdir(), 'rustrak-tree-'));
    for (const f of files) {
      mkdirSync(dirname(join(dir, 'src/server', f)), { recursive: true });
      writeFileSync(join(dir, 'src/server', f), '');
    }
    return dir;
  }

  it('declares every file under src/server: no lib.rs, no mod.rs', () => {
    const dir = server([
      'routes/hits.rs',
      'routes/admin/users.rs',
      'models/tick.rs',
      'models/hit.rs',
    ]);
    generate(dir, config);
    const lib = readFileSync(join(dir, '.rustrak', 'lib.rs'), 'utf8');
    expect(lib).toContain('rustrak_plugin::config!();');
    expect(lib).toContain(
      [
        '#[path = "../src/server/routes"]',
        'pub mod routes {',
        '    #[path = "admin"]',
        '    pub mod admin {',
        '        #[path = "users.rs"]',
        '        pub mod users;',
        '    }',
        '    #[path = "hits.rs"]',
        '    pub mod hits;',
        '}',
      ].join('\n'),
    );
    expect(lib).toContain('#[path = "../src/server/models"]\npub mod models {');
  });

  it('refuses a lib.rs or mod.rs: Rustrak writes the tree', () => {
    const dir = server(['routes/mod.rs', 'routes/hits.rs']);
    expect(() => generate(dir, config)).toThrow(
      /src\/server\/routes\/mod\.rs: Rustrak declares the modules/,
    );
  });

  it('declares a module named by a Rust keyword as a raw identifier', () => {
    const dir = server(['models/type.rs']);
    generate(dir, config);
    const lib = readFileSync(join(dir, '.rustrak', 'lib.rs'), 'utf8');
    expect(lib).toContain('#[path = "type.rs"]\n    pub mod r#type;');
  });

  it('refuses a file whose name is not a snake_case module', () => {
    const dir = server(['routes/my-hits.rs']);
    expect(() => generate(dir, config)).toThrow(
      /my-hits\.rs: a module name is snake_case/,
    );
  });
});
